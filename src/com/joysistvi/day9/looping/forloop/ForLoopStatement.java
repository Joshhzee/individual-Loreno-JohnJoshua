package com.joysistvi.day9.looping.forloop;

public class ForLoopStatement {

    public static void main(String[] args) {

        // Print the first 10 even numbers

        for (int i = 1; i <= 20; i++) {

            if (i % 2 == 0) {
                System.out.println(i);
            }

        }

    }
}